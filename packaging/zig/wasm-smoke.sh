#!/usr/bin/env bash
# wasm32-wasi-musl smoke: prove the wasm target compiles, links and runs under
# a WASI runtime. Three checks:
#
#   1. wasm:  demo program -> demo.wasm, run under wasmtime
#   2. parity: the same program compiled natively; wasm and native output must
#      be byte-identical
#   3. fixture: hello.py --call add --args '[20, 22]' as wasm -> prints 42
#
# The demo exercises a loop (fib), str methods (split/upper), try/except
# (int("abc") -> ValueError) and an int print. try/except lowers to the wasm
# exception-handling proposal, so wasmtime >= v50 is required; older runtimes
# fail with "exceptions proposal not enabled".
#
#   packaging/zig/wasm-smoke.sh   # needs `zig` and `wasmtime` on PATH
#                                 # (WASMTIME=/path/to/wasmtime overrides)
#
# Unlike smoke.sh there are no committed .ll fixtures here: everything is
# regenerated by the compiler in the script itself.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
root="$(cd "$here/../.." && pwd)"

fail() { echo "WASM SMOKE FAIL: $*" >&2; exit 1; }
command -v zig >/dev/null || fail "zig is not on PATH"

wasmtime="${WASMTIME:-wasmtime}"
if ! command -v "$wasmtime" >/dev/null; then
    echo "note: wasmtime is not on PATH, the wasm target is compile-only" >&2
    echo "WASM SMOKE OK ($(zig version), compile-only)"
    exit 0
fi

# wasmtime >= v50: the exception-handling proposal must be on by default.
wt_version="$("$wasmtime" --version 2>/dev/null | awk '{print $2}')"
wt_major="${wt_version%%.*}"
if [ -z "$wt_major" ] || [ "$wt_major" = "v" ] || ! [ "$wt_major" -ge 50 ] 2>/dev/null; then
    echo "note: $wasmtime --version reports '$wt_version', need >= 50 (exceptions proposal); continuing and trusting the run" >&2
fi

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

cat > "$work/demo.py" <<'PY'
def fib(n: int) -> int:
    a, b = 0, 1
    for _ in range(n):
        a, b = b, a + b
    return a


def main() -> None:
    print(fib(10))
    parts: list[str] = "a,b,c".split(",")
    print(parts[1].upper())
    try:
        int("abc")
    except ValueError:
        print("caught ValueError")
    print(1234)


if __name__ == "__main__":
    main()
PY

cd "$root"

# 1. wasm build and run.
uv run pyscriptc compile "$work/demo.py" --emit bin --skip-check \
    --target wasm32-wasi-musl -o "$work/demo" >/dev/null \
    || fail "wasm compile failed for demo.py"
[ -s "$work/demo.wasm" ] || fail "wasm compile produced no demo.wasm"
"$wasmtime" "$work/demo.wasm" > "$work/wasm.out" 2> "$work/wasm.err" \
    || fail "wasmtime failed to run demo.wasm: $(cat "$work/wasm.err")"
[ -s "$work/wasm.out" ] || fail "wasm run produced no output"

# 2. native build of the same program; outputs must be byte-identical.
uv run pyscriptc compile "$work/demo.py" --emit bin --skip-check \
    -o "$work/demo-native" >/dev/null \
    || fail "native compile failed for demo.py"
"$work/demo-native" > "$work/native.out" 2>"$work/native.err" \
    || fail "native demo did not run: $(cat "$work/native.err")"
if ! diff -u "$work/native.out" "$work/wasm.out"; then
    fail "native and wasm output differ"
fi

# 3. committed fixture as wasm: add(20, 22) -> 42. Generated fresh here; the
# committed packaging/zig/hello.ll is a stale standalone fixture and is not
# used.
uv run pyscriptc compile "$here/hello.py" --emit bin --call add --args '[20, 22]' \
    --skip-check --target wasm32-wasi-musl -o "$work/hello" >/dev/null \
    || fail "wasm compile failed for hello.py"
got="$("$wasmtime" "$work/hello.wasm")" \
    || fail "wasmtime failed to run hello.wasm"
[ "$got" = "42" ] || fail "hello printed '$got', expected 42"

# 4. WASI 0.2: the same demo compiled to a component (wasm32-wasi-p2 wraps
# the p1 core module with wasm-tools + the pinned wasmtime adapter) and run
# under wasmtime; the output must be byte-identical to the native build.
if command -v wasm-tools >/dev/null; then
    uv run pyscriptc compile "$work/demo.py" --emit bin --skip-check \
        --target wasm32-wasi-p2 -o "$work/demo-p2" >/dev/null \
        || fail "wasi-p2 compile failed for demo.py"
    [ -s "$work/demo-p2.wasm" ] || fail "wasi-p2 compile produced no demo-p2.wasm"
    # A component's magic is the wasm magic followed by version 0x000d (13);
    # a core module has version 0x0001. The odd byte order is the spec's.
    magic="$(od -An -tx1 -N8 "$work/demo-p2.wasm" | tr -d ' \\n')"
    [ "${magic:0:16}" = "0061736d0d000100" ] \
        || fail "demo-p2.wasm is not a WASI 0.2 component (magic $magic)"
    "$wasmtime" "$work/demo-p2.wasm" > "$work/p2.out" 2> "$work/p2.err" \
        || fail "wasmtime failed to run the wasi-p2 component: $(cat "$work/p2.err")"
    if ! diff -u "$work/native.out" "$work/p2.out"; then
        fail "native and wasi-p2 output differ"
    fi

    # 5. generators on 0.2: the resumable lowering survives the wrap.
    cat > "$work/gen.py" <<'PY'
from typing import Iterator


def count(n: int) -> Iterator[int]:
    i: int = 0
    while i < n:
        yield i
        i = i + 1


def main() -> None:
    total: int = 0
    for v in count(5):
        total = total + v
    print(total)


if __name__ == "__main__":
    main()
PY
    uv run pyscriptc compile "$work/gen.py" --emit bin --skip-check \
        --target wasm32-wasi-p2 -o "$work/gen-p2" >/dev/null \
        || fail "wasi-p2 compile failed for gen.py"
    got="$("$wasmtime" "$work/gen-p2.wasm")" \
        || fail "wasmtime failed to run the generator component"
    [ "$got" = "10" ] || fail "generator printed '$got', expected 10"

    echo "wasi-p2 OK (component run + parity + generators)"
else
    echo "note: wasm-tools is not on PATH, the wasi-p2 lane is skipped" >&2
fi

echo "WASM SMOKE OK ($(zig version))"
