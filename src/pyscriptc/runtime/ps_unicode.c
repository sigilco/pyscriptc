void ps_unicode_category(int64_t n, const char *s, PsBuf *out) {
    uint32_t cp = ps_uni_one(n, s, "unicodedata.category() argument is not a one-character string");
    uint16_t packed = ps_uni_cat_packed(cp);
    char buf[2];
    buf[0] = (char)(packed >> 8);
    buf[1] = (char)packed;
    ps_buf_copy(out, buf, 2);
}

