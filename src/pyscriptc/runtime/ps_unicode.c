/* Unicode properties over the whole code-point space, from CPython 3.14
   unicodedata (unidata_version 16.0.0).

   The tables live in ps_unicode_data.c (generated by
   scripts/gen_unicode_tables.py) and cover every code point from
   U+0000 to U+10FFFF. A `str` is a UTF-8 byte buffer, so every entry
   point decodes its argument as code points before it looks a code
   point up.

   The Hangul syllable block and the two CJK ideograph name families are
   algorithmic: the tables carry no row for them and the functions build
   the answer by arithmetic. */

#include "ps_rt.h"

#include "ps_unicode_data.c"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* ---- the sorted-record and run lookups ---- */

/* The value of the run that covers a code point, or 0 (the Cn
   unassigned default) when no run does. */
static uint32_t ps_uni_run_value(const PsUniRun *table, int64_t count, uint32_t cp) {
    int64_t lo = 0;
    int64_t hi = count - 1;
    while (lo <= hi) {
        int64_t mid = lo + (hi - lo) / 2;
        if (cp < table[mid].lo) {
            hi = mid - 1;
        } else if (cp > table[mid].hi) {
            lo = mid + 1;
        } else {
            return table[mid].val;
        }
    }
    return 0;
}

static const void *ps_uni_find(const void *base, int64_t count, int64_t stride, uint32_t cp) {
    int64_t lo = 0;
    int64_t hi = count - 1;
    while (lo <= hi) {
        int64_t mid = lo + (hi - lo) / 2;
        uint32_t key = *(const uint32_t *)((const char *)base + (int64_t)mid * stride);
        if (cp < key) {
            hi = mid - 1;
        } else if (cp > key) {
            lo = mid + 1;
        } else {
            return (const char *)base + (int64_t)mid * stride;
        }
    }
    return NULL;
}

/* The general category as the two letters, packed the way CPython
   prints them (the first letter in the high byte). The table stores the
   category as (first - 'A') * 26 + (second - 'A'), which does not fit a
   nibble pair (Zs is 450), so the letters are recovered by division. */
static uint16_t ps_uni_cat_packed(uint32_t cp) {
    uint32_t code = ps_uni_run_value(ps_uni_cat, PS_UNI_CAT_N, cp);
    if (code == 0) {
        return 0x436Eu; /* "Cn", the unassigned default */
    }
    return (uint16_t)((((code / 27) + 'A') << 8) | ((code % 27) - 1 + 'a'));
}

int ps_str_printable(uint32_t cp) {
    if (cp == 0x20) {
        return 1;
    }
    uint16_t packed = ps_uni_cat_packed(cp);
    char c0 = (char)(packed >> 8);
    /* The control and format characters, the surrogates, the private
       use and the unassigned escape, and every separator (Zs, Zl, Zp)
       other than the plain space the caller answered. */
    if (c0 == 'C' || c0 == 'Z') {
        return 0;
    }
    return 1;
}

/* ---- the UTF-8 decoding the entry points share ---- */

/* The number of bytes the code point at the head of the buffer takes,
   or 0 when the buffer does not start with a well-formed sequence. */
static int ps_uni_width(const char *p, int64_t n, uint32_t *out) {
    if (n <= 0) {
        return 0;
    }
    unsigned char lead = (unsigned char)p[0];
    if (lead < 0x80) {
        *out = lead;
        return 1;
    }
    int width;
    uint32_t cp;
    if (lead >= 0xC2 && lead <= 0xDF) {
        width = 2;
        cp = lead & 0x1Fu;
    } else if (lead >= 0xE0 && lead <= 0xEF) {
        width = 3;
        cp = lead & 0x0Fu;
    } else if (lead >= 0xF0 && lead <= 0xF4) {
        width = 4;
        cp = lead & 0x07u;
    } else {
        return 0;
    }
    if (n < width) {
        return 0;
    }
    for (int k = 1; k < width; k++) {
        unsigned char cc = (unsigned char)p[k];
        if ((cc & 0xC0) != 0x80) {
            return 0;
        }
        cp = (cp << 6) | (uint32_t)(cc & 0x3Fu);
    }
    if (width == 2 && cp < 0x80) {
        return 0;
    }
    if (width == 3 && cp < 0x800) {
        return 0;
    }
    if (width == 4 && cp < 0x10000) {
        return 0;
    }
    if (cp > 0x10FFFF || (cp >= 0xD800 && cp <= 0xDFFF)) {
        return 0;
    }
    *out = cp;
    return width;
}

/* The one-code-point argument the property functions take. */
static uint32_t ps_uni_one(int64_t n, const char *s, const char *what) {
    uint32_t cp = 0;
    int width = ps_uni_width(s, n, &cp);
    if (width == 0 || width != n) {
        ps_raise_cstr(PS_VALUE, what);
    }
    return cp;
}

/* The UTF-8 encoding of one code point into a four byte buffer: the
   number of bytes written. */
static int ps_uni_encode(uint32_t cp, char *buf) {
    if (cp < 0x80) {
        buf[0] = (char)cp;
        return 1;
    }
    if (cp < 0x800) {
        buf[0] = (char)(0xC0 | (cp >> 6));
        buf[1] = (char)(0x80 | (cp & 0x3Fu));
        return 2;
    }
    if (cp < 0x10000) {
        buf[0] = (char)(0xE0 | (cp >> 12));
        buf[1] = (char)(0x80 | ((cp >> 6) & 0x3Fu));
        buf[2] = (char)(0x80 | (cp & 0x3Fu));
        return 3;
    }
    buf[0] = (char)(0xF0 | (cp >> 18));
    buf[1] = (char)(0x80 | ((cp >> 12) & 0x3Fu));
    buf[2] = (char)(0x80 | ((cp >> 6) & 0x3Fu));
    buf[3] = (char)(0x80 | (cp & 0x3Fu));
    return 4;
}

/* The UTF-8 encoding of one code point, appended to the grow buffer. */
static void ps_uni_put(PsGrow *grow, uint32_t cp) {
    if (cp < 0x80) {
        ps_grow_byte(grow, (unsigned char)cp);
    } else if (cp < 0x800) {
        ps_grow_byte(grow, (unsigned char)(0xC0 | (cp >> 6)));
        ps_grow_byte(grow, (unsigned char)(0x80 | (cp & 0x3Fu)));
    } else if (cp < 0x10000) {
        ps_grow_byte(grow, (unsigned char)(0xE0 | (cp >> 12)));
        ps_grow_byte(grow, (unsigned char)(0x80 | ((cp >> 6) & 0x3Fu)));
        ps_grow_byte(grow, (unsigned char)(0x80 | (cp & 0x3Fu)));
    } else {
        ps_grow_byte(grow, (unsigned char)(0xF0 | (cp >> 18)));
        ps_grow_byte(grow, (unsigned char)(0x80 | ((cp >> 12) & 0x3Fu)));
        ps_grow_byte(grow, (unsigned char)(0x80 | ((cp >> 6) & 0x3Fu)));
        ps_grow_byte(grow, (unsigned char)(0x80 | (cp & 0x3Fu)));
    }
}

