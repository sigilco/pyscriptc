void ps_unicode_lookup(int64_t n, const char *s, PsBuf *out) {
    int lo = 0;
    int hi = ps_look_n;
    while (lo < hi) {
        int mid = lo + (hi - lo) / 2;
        int64_t len = (int64_t)ps_look_len[mid];
        int cmp = memcmp(s, ps_look_blob + ps_look_off[mid], (size_t)(n < len ? n : len));
        if (cmp == 0) {
            cmp = (n > len) - (n < len);
        }
        if (cmp == 0) {
            unsigned char ch = (unsigned char)ps_look_cp[mid];
            ps_buf_copy(out, (const char *)&ch, 1);
            return;
        }
        if (cmp < 0) {
            hi = mid;
        } else {
            lo = mid + 1;
        }
    }
    ps_raise_cstr(PS_VALUE, "undefined character name");
}

