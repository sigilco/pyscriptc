/* The decomposition of one code point, as the space-separated hex
   sequence CPython returns (the compatibility tag is not part of the
   answer). The Hangul syllables decompose arithmetically. */
void ps_unicode_decomposition(int64_t n, const char *s, PsBuf *out) {
    uint32_t cp = ps_uni_one(n, s, "unicodedata.decomposition() argument is not a one-character string");
    const char *tag = NULL;
    int taglen = 0;
    uint32_t seq[18];
    int len = 0;
    if (cp >= PS_UNI_SBASE && cp < PS_UNI_SBASE + PS_UNI_SCOUNT) {
        uint32_t index = cp - PS_UNI_SBASE;
        seq[len++] = PS_UNI_LBASE + index / PS_UNI_NCOUNT;
        seq[len++] = PS_UNI_VBASE + (index % PS_UNI_NCOUNT) / PS_UNI_TCOUNT;
        if (index % PS_UNI_TCOUNT) {
            seq[len++] = PS_UNI_TBASE + index % PS_UNI_TCOUNT;
        }
    } else {
        const PsUniDec *row = ps_uni_find(ps_uni_decomp, PS_UNI_DECOMP_N, sizeof(PsUniDec), cp);
        if (row != NULL) {
            static const char *const tags[] = {"<font>", "<noBreak>", "<initial>", "<medial>",
                                               "<final>", "<isolated>", "<circle>", "<super>",
                                               "<sub>", "<vertical>", "<wide>", "<narrow>",
                                               "<small>", "<square>", "<fraction>", "<compat>"};
            if (row->compat) {
                tag = tags[row->compat - 1];
                taglen = (int)strlen(tag);
            }
            for (uint32_t k = 0; k < row->len && k < 18; k++) {
                uint32_t value = 0;
                for (int b = 0; b < 4; b++) {
                    value = (value << 8) | (unsigned char)ps_uni_decomp_pool[(row->off + k) * 4 + b];
                }
                seq[len++] = value;
            }
        }
    }
    char buf[160];
    int64_t w = 0;
    if (tag != NULL) {
        memcpy(buf, tag, (size_t)taglen);
        w = taglen;
    }
    for (int k = 0; k < len; k++) {
        w += snprintf(buf + w, sizeof buf - (size_t)w, "%s%04X", (k || tag) ? " " : "", seq[k]);
    }
    ps_buf_copy(out, buf, w);
}

/* The name of one code point. The Hangul syllables and the two CJK
   ideograph families are algorithmic; everything else comes from the
   prefix-compressed name table. */
void ps_unicode_name(int64_t n, const char *s, int64_t has_default, int64_t dn, const char *def, PsBuf *out) {
    uint32_t cp = ps_uni_one(n, s, "unicodedata.name() argument is not a one-character string");
    char buf[128];
    if (cp >= PS_UNI_SBASE && cp < PS_UNI_SBASE + PS_UNI_SCOUNT) {
        /* The Hangul syllable names spell out the chosen jamo names. */
        static const char *const lparts[] = {"G", "GG", "N", "D", "DD", "R", "M", "B", "BB", "S",
                                             "SS", "", "J", "JJ", "C", "K", "T", "P", "H"};
        static const char *const vparts[] = {"A", "AE", "YA", "YAE", "EO", "E", "YEO", "YE", "O", "WA",
                                             "WAE", "OE", "YO", "U", "WEO", "WE", "WI", "YU", "EU", "YI", "I"};
        static const char *const tparts[] = {"", "G", "GG", "GS", "N", "NJ", "NH", "D", "L", "LG", "LM",
                                             "LB", "LS", "LT", "LP", "LH", "M", "B", "BS", "S", "SS",
                                             "NG", "J", "C", "K", "T", "P", "H"};
        uint32_t index = cp - PS_UNI_SBASE;
        snprintf(buf, sizeof buf, "HANGUL SYLLABLE %s%s%s", lparts[index / PS_UNI_NCOUNT],
                 vparts[(index % PS_UNI_NCOUNT) / PS_UNI_TCOUNT], tparts[index % PS_UNI_TCOUNT]);
        ps_buf_copy(out, buf, (int64_t)strlen(buf));
        return;
    }
    /* The two CJK ideograph families: the name is the prefix and the
       code point in hex; the ranges come from the generated table. */
    {
        int64_t lo = 0;
        int64_t hi = PS_UNI_CJK_N - 1;
        while (lo <= hi) {
            int64_t mid = (lo + hi) / 2;
            const PsUniCjk *range = &ps_uni_cjk[mid];
            if (cp < range->lo) {
                hi = mid - 1;
            } else if (cp > range->hi) {
                lo = mid + 1;
            } else {
                const char *prefix = ps_uni_cjk_prefixes[range->family];
                snprintf(buf, sizeof buf, "%s%04X", prefix, cp);
                ps_buf_copy(out, buf, (int64_t)strlen(buf));
                return;
            }
        }
    }
    const PsUniName *row = ps_uni_find(ps_uni_name, PS_UNI_NAME_N, sizeof(PsUniName), cp);
    if (row == NULL) {
        if (has_default) {
            ps_buf_copy(out, def, dn);
            return;
        }
        ps_raise_cstr(PS_VALUE, "no such name");
    }
    const PsUniPrefix *prefix = &ps_uni_name_prefix[row->pidx];
    char *w = buf;
    memcpy(w, ps_uni_name_pool + prefix->off, prefix->len);
    w += prefix->len;
    memcpy(w, ps_uni_name_pool + row->soff, row->slen);
    w += row->slen;
    *w = 0;
    ps_buf_copy(out, buf, (int64_t)(w - buf));
}

/* The name lookup: the reverse of the name function. The stored names
   are walked as prefix + suffix; the algorithmic names (the Hangul
   syllables, the two CJK ideograph families) are matched by
   construction, and the formal aliases come from the alias table. */
void ps_unicode_lookup(int64_t n, const char *s, PsBuf *out) {
    /* The algorithmic names first: the Hangul syllables. */
    if (n > 16 && memcmp(s, "HANGUL SYLLABLE ", 16) == 0) {
        static const char *const lparts[] = {"G", "GG", "N", "D", "DD", "R", "M", "B", "BB", "S",
                                             "SS", "", "J", "JJ", "C", "K", "T", "P", "H"};
        static const char *const vparts[] = {"A", "AE", "YA", "YAE", "EO", "E", "YEO", "YE", "O", "WA",
                                             "WAE", "OE", "YO", "U", "WEO", "WE", "WI", "YU", "EU", "YI", "I"};
        static const char *const tparts[] = {"", "G", "GG", "GS", "N", "NJ", "NH", "D", "L", "LG", "LM",
                                             "LB", "LS", "LT", "LP", "LH", "M", "B", "BS", "S", "SS",
                                             "NG", "J", "C", "K", "T", "P", "H"};
        const char *body = s + 16;
        int64_t blen = n - 16;
        for (uint32_t l = 0; l < PS_UNI_LCOUNT; l++) {
            size_t ll = strlen(lparts[l]);
            if ((int64_t)ll > blen || memcmp(body, lparts[l], ll) != 0) {
                continue;
            }
            for (uint32_t v = 0; v < PS_UNI_VCOUNT; v++) {
                size_t vl = strlen(vparts[v]);
                if ((int64_t)(ll + vl) > blen || memcmp(body + ll, vparts[v], vl) != 0) {
                    continue;
                }
                for (uint32_t t = 0; t < PS_UNI_TCOUNT; t++) {
                    size_t tl = strlen(tparts[t]);
                    if ((int64_t)(ll + vl + tl) != blen || memcmp(body + ll + vl, tparts[t], tl) != 0) {
                        continue;
                    }
                    uint32_t cp = PS_UNI_SBASE + (l * PS_UNI_VCOUNT + v) * PS_UNI_TCOUNT + t;
                    char one[4];
                    int width = ps_uni_encode(cp, one);
                    ps_buf_copy(out, one, width);
                    return;
                }
            }
        }
    }
    /* The two CJK ideograph families: the name is the prefix and the
       code point in hex. The ranges come from the generated table. */
    for (int64_t k = 0; k < PS_UNI_CJK_N; k++) {
        const PsUniCjk *range = &ps_uni_cjk[k];
        const char *prefix = ps_uni_cjk_prefixes[range->family];
        int64_t plen = (int64_t)strlen(prefix);
        if (n <= plen || memcmp(s, prefix, (size_t)plen) != 0) {
            continue;
        }
        const char *hexpart = s + plen;
        int64_t hlen = n - plen;
        if (hlen != 4 && hlen != 5) {
            continue;
        }
        uint32_t cp = 0;
        int ok = 1;
        for (int64_t i = 0; i < hlen; i++) {
            char c = hexpart[i];
            uint32_t digit;
            if (c >= '0' && c <= '9') {
                digit = (uint32_t)(c - '0');
            } else if (c >= 'A' && c <= 'F') {
                digit = (uint32_t)(c - 'A' + 10);
            } else {
                ok = 0;
                break;
            }
            cp = cp * 16 + digit;
        }
        if (ok && cp >= range->lo && cp <= range->hi) {
            char one[4];
            int width = ps_uni_encode(cp, one);
            ps_buf_copy(out, one, width);
            return;
        }
    }
    /* The stored names: the longest prefix match wins, so the walk goes
       through the prefix table and compares the shared prefix first. */
    for (int64_t p = 0; p < PS_UNI_NAME_PREFIX_N; p++) {
        const PsUniPrefix *prefix = &ps_uni_name_prefix[p];
        if (n < (int64_t)prefix->len || memcmp(s, ps_uni_name_pool + prefix->off, prefix->len) != 0) {
            continue;
        }
        /* The candidates under this prefix: a contiguous span of the
           name table. The suffixes are unique per run, so the first
           match inside the span is the answer. */
        for (int64_t i = 0; i < PS_UNI_NAME_N; i++) {
            const PsUniName *row = &ps_uni_name[i];
            if (row->pidx != p) {
                continue;
            }
            int64_t total = (int64_t)prefix->len + row->slen;
            if (total != n) {
                continue;
            }
            if (memcmp(s + prefix->len, ps_uni_name_pool + row->soff, row->slen) == 0) {
                char one[4];
                int width = ps_uni_encode(row->cp, one);
                ps_buf_copy(out, one, width);
                return;
            }
        }
    }
    /* The formal aliases. */
    for (int64_t i = 0; i < PS_UNI_ALIAS_N; i++) {
        const PsUniAlias *row = &ps_uni_alias[i];
        if ((int64_t)row->len != n) {
            continue;
        }
        if (memcmp(s, ps_uni_alias_pool + row->off, row->len) == 0) {
            char one[4];
            int width = ps_uni_encode(row->cp, one);
            ps_buf_copy(out, one, width);
            return;
        }
    }
    /* CPython raises a KeyError whose argument is the message
       `undefined character name 'NOPE'`; the runtime prints a KeyError
       argument as its repr, so the message carries no outer quotes. The
       name is quoted with the single quotes, the way CPython spells it. */
    {
        char msg[256];
        int64_t w = snprintf(msg, sizeof msg, "undefined character name '");
        for (int64_t i = 0; i < n && w < (int64_t)sizeof msg - 8; i++) {
            char c = s[i];
            if (c == '\'' || c == '\\') {
                msg[w++] = '\\';
                if (w >= (int64_t)sizeof msg - 8) {
                    break;
                }
            }
            msg[w++] = c;
        }
        snprintf(msg + w, sizeof msg - (size_t)w, "'");
        ps_raise_cstr(PS_KEY, msg);
    }
}

void ps_unicode_version(PsBuf *out) {
    ps_buf_copy(out, PS_UNICODE_VERSION, (int64_t)strlen(PS_UNICODE_VERSION));
}

/* ---- the normalization ---- */

/* The decomposition of one code point, appended as code points. The
   Hangul syllables decompose arithmetically; a compatibility
   decomposition applies only when the form asks for it. */
static void ps_uni_decompose_cp(uint32_t **cps, int64_t *len, int64_t *cap, uint32_t cp, int compat) {
    if (cp >= PS_UNI_SBASE && cp < PS_UNI_SBASE + PS_UNI_SCOUNT) {
        uint32_t index = cp - PS_UNI_SBASE;
        ps_uni_decompose_cp(cps, len, cap, PS_UNI_LBASE + index / PS_UNI_NCOUNT, compat);
        ps_uni_decompose_cp(cps, len, cap, PS_UNI_VBASE + (index % PS_UNI_NCOUNT) / PS_UNI_TCOUNT, compat);
        if (index % PS_UNI_TCOUNT) {
            ps_uni_decompose_cp(cps, len, cap, PS_UNI_TBASE + index % PS_UNI_TCOUNT, compat);
        }
        return;
    }
    const PsUniDec *row = ps_uni_find(ps_uni_decomp, PS_UNI_DECOMP_N, sizeof(PsUniDec), cp);
    if (row == NULL || (row->compat && !compat)) {
        if (*len == *cap) {
            *cap *= 2;
            uint32_t *grown = realloc(*cps, (size_t)*cap * sizeof(uint32_t));
            if (grown == NULL) {
                abort();
            }
            *cps = grown;
        }
        (*cps)[(*len)++] = cp;
        return;
    }
    for (uint32_t k = 0; k < row->len; k++) {
        uint32_t value = 0;
        for (int b = 0; b < 4; b++) {
            value = (value << 8) | (unsigned char)ps_uni_decomp_pool[(row->off + k) * 4 + b];
        }
        ps_uni_decompose_cp(cps, len, cap, value, compat);
    }
}

/* The canonical ordering: the combining marks of each run are sorted by
   their combining class, stably (an insertion sort, which is what the
   reference algorithm describes). */
static void ps_uni_canonical_order(uint32_t *cps, int64_t n) {
    for (int64_t i = 1; i < n; i++) {
        uint32_t cp = cps[i];
        uint32_t cls = ps_uni_run_value(ps_uni_ccc, PS_UNI_CCC_N, cp);
        if (cls == 0) {
            continue;
        }
        int64_t j = i - 1;
        while (j >= 0 && ps_uni_run_value(ps_uni_ccc, PS_UNI_CCC_N, cps[j]) > cls) {
            cps[j + 1] = cps[j];
            j--;
        }
        cps[j + 1] = cp;
    }
}

/* The composition walk (the reference algorithm from UAX #15): the
   current starter stays in place, a composable mark replaces it in
   place, and a class-0 code point becomes the next starter. The
   composition pairs are searched from the pair table, and the Hangul
   jamo compose by arithmetic. */
static uint32_t ps_uni_compose(uint32_t starter, uint32_t combining) {
    if (PS_UNI_TBASE < combining && combining < PS_UNI_TBASE + PS_UNI_TCOUNT &&
        starter >= PS_UNI_SBASE && starter < PS_UNI_SBASE + PS_UNI_SCOUNT &&
        (starter - PS_UNI_SBASE) % PS_UNI_TCOUNT == 0) {
        return starter + (combining - PS_UNI_TBASE);
    }
    if (starter >= PS_UNI_LBASE && starter < PS_UNI_LBASE + PS_UNI_LCOUNT &&
        combining >= PS_UNI_VBASE && combining < PS_UNI_VBASE + PS_UNI_VCOUNT) {
        return PS_UNI_SBASE +
               ((starter - PS_UNI_LBASE) * PS_UNI_VCOUNT + (combining - PS_UNI_VBASE)) * PS_UNI_TCOUNT;
    }
    int64_t lo = 0;
    int64_t hi = PS_UNI_COMP_N - 1;
    while (lo <= hi) {
        int64_t mid = lo + (hi - lo) / 2;
        const PsUniComp *row = &ps_uni_comp[mid];
        if (starter < row->starter || (starter == row->starter && combining < row->comp)) {
            hi = mid - 1;
        } else if (starter > row->starter || (starter == row->starter && combining > row->comp)) {
            lo = mid + 1;
        } else {
            return row->out;
        }
    }
    return 0;
}

static int64_t ps_uni_compose_all(uint32_t *cps, int64_t n, uint32_t **out) {
    if (n == 0) {
        *out = cps;
        return 0;
    }
    uint32_t *res = malloc((size_t)n * sizeof(uint32_t));
    if (res == NULL) {
        abort();
    }
    int64_t len = 0;
    res[len++] = cps[0];
    int64_t starter_pos = 0;
    uint32_t starter = cps[0];
    uint32_t last = ps_uni_run_value(ps_uni_ccc, PS_UNI_CCC_N, starter);
    if (last != 0) {
        last = 256;
    }
    for (int64_t i = 1; i < n; i++) {
        uint32_t ch = cps[i];
        uint32_t cls = ps_uni_run_value(ps_uni_ccc, PS_UNI_CCC_N, ch);
        uint32_t composite = ps_uni_compose(starter, ch);
        if (composite != 0 && (last < cls || last == 0)) {
            res[starter_pos] = composite;
            starter = composite;
            continue;
        }
        if (cls == 0) {
            starter_pos = len;
            starter = ch;
        }
        last = cls;
        res[len++] = ch;
    }
    free(cps);
    *out = res;
    return len;
}

/* The form id the lowering hands over: 0 NFC, 1 NFD, 2 NFKC, 3 NFKD.
   Returns -1 for an unknown form (the caller raises). */
static int ps_uni_form_id(int64_t fn, const char *form) {
    if (fn == 3 && memcmp(form, "NFC", 3) == 0) {
        return 0;
    }
    if (fn == 3 && memcmp(form, "NFD", 3) == 0) {
        return 1;
    }
    if (fn == 4 && memcmp(form, "NFKC", 4) == 0) {
        return 2;
    }
    if (fn == 4 && memcmp(form, "NFKD", 4) == 0) {
        return 3;
    }
    return -1;
}

/* The shared normalization walk: decompose (compatibly when the form
   asks), canonically order, and compose again for the composed forms. */
static void ps_uni_normalize(int form, int64_t n, const char *s, PsBuf *out) {
    int compat = form >= 2;
    int compose = form == 0 || form == 2;
    int64_t cap = n + 16;
    uint32_t *cps = malloc((size_t)cap * sizeof(uint32_t));
    if (cps == NULL) {
        abort();
    }
    int64_t len = 0;
    int64_t i = 0;
    while (i < n) {
        uint32_t cp = 0;
        int width = ps_uni_width(s + i, n - i, &cp);
        if (width == 0) {
            free(cps);
            ps_raise_cstr(PS_VALUE, "invalid continuation byte");
        }
        ps_uni_decompose_cp(&cps, &len, &cap, cp, compat);
        i += width;
    }
    ps_uni_canonical_order(cps, len);
    uint32_t *res = cps;
    if (compose) {
        len = ps_uni_compose_all(cps, len, &res);
    }
    PsGrow grow;
    ps_grow_init(&grow);
    for (int64_t k = 0; k < len; k++) {
        ps_uni_put(&grow, res[k]);
    }
    free(res);
    ps_grow_finish(&grow, out);
}

void ps_unicode_normalize(int64_t fn, const char *form, int64_t n, const char *s, PsBuf *out) {
    int id = ps_uni_form_id(fn, form);
    if (id < 0) {
        ps_raise_cstr(PS_VALUE, "invalid normalization form");
    }
    ps_uni_normalize(id, n, s, out);
}

/* Whether a string is already in the given form: the walk above runs on
   the string and the answer is whether it came back unchanged. */
int32_t ps_unicode_is_normalized(int64_t fn, const char *form, int64_t n, const char *s) {
    int id = ps_uni_form_id(fn, form);
    if (id < 0) {
        ps_raise_cstr(PS_VALUE, "invalid normalization form");
    }
    PsBuf normalized;
    ps_uni_normalize(id, n, s, &normalized);
    int32_t ok = normalized.len == n && memcmp(normalized.data, s, (size_t)n) == 0;
    free(normalized.data);
    return ok;
}

/* ---- the shared repr engine ---- */

/* CPython's `repr` of a str: the shortest of '...' / "..." carries the
   string, backslashes and the active quote escape, \n \r \t keep their
   letter names, printable code points print as themselves and the rest
   escape as \xNN (below U+0100), \uNNNN (below U+010000) or \UNNNNNNNN.
   Shared by the repr() builtin, the tuple display and the !r conversion. */
void ps_repr_str(int64_t n, const char *p, PsBuf *out) {
    char *q = malloc((size_t)n * 10 + 3);
    if (q == NULL) {
        abort();
    }
    char *w = q;
    int quote = '\'';
    if (memchr(p, '\'', (size_t)n) != NULL && memchr(p, '"', (size_t)n) == NULL) {
        quote = '"';
    }
    *w++ = (char)quote;
    static const char hex[] = "0123456789abcdef";
    int64_t i = 0;
    while (i < n) {
        unsigned char c = (unsigned char)p[i];
        if (c < 0x80) {
            if (c == (unsigned char)quote || c == '\\') {
                *w++ = '\\';
                *w++ = (char)c;
            } else if (c == '\n') {
                *w++ = '\\';
                *w++ = 'n';
            } else if (c == '\r') {
                *w++ = '\\';
                *w++ = 'r';
            } else if (c == '\t') {
                *w++ = '\\';
                *w++ = 't';
            } else if (c >= 0x20 && c != 0x7f) {
                *w++ = (char)c;
            } else {
                *w++ = '\\';
                *w++ = 'x';
                *w++ = hex[c >> 4];
                *w++ = hex[c & 15];
            }
            i++;
            continue;
        }
        uint32_t cp = 0;
        int width = ps_uni_width(p + i, n - i, &cp);
        if (width == 0) {
            width = 1;
            cp = c;
        }
        if (ps_str_printable(cp) > 0) {
            memcpy(w, p + i, (size_t)width);
            w += width;
        } else if (cp < 0x100) {
            *w++ = '\\';
            *w++ = 'x';
            *w++ = hex[(cp >> 4) & 15];
            *w++ = hex[cp & 15];
        } else if (cp < 0x10000) {
            *w++ = '\\';
            *w++ = 'u';
            *w++ = hex[(cp >> 12) & 15];
            *w++ = hex[(cp >> 8) & 15];
            *w++ = hex[(cp >> 4) & 15];
            *w++ = hex[cp & 15];
        } else {
            *w++ = '\\';
            *w++ = 'U';
            for (int shift = 28; shift >= 0; shift -= 4) {
                *w++ = hex[(cp >> shift) & 15];
            }
        }
        i += width;
    }
    *w++ = (char)quote;
    out->len = w - q;
    out->data = q;
}
