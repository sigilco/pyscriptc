static unsigned char ps_one(int64_t n, const char *s, const char *what) {
    if (n != 1) {
        ps_raise_cstr(PS_VALUE, what);
    }
    return (unsigned char)s[0];
}

static int ps_form_id(int64_t n, const char *s) {
    if (n == 3 && memcmp(s, "NFC", 3) == 0) {
        return 0;
    }
    if (n == 3 && memcmp(s, "NFD", 3) == 0) {
        return 1;
    }
    if (n == 4 && memcmp(s, "NFKC", 4) == 0) {
        return 2;
    }
    if (n == 4 && memcmp(s, "NFKD", 4) == 0) {
        return 3;
    }
    ps_raise_cstr(PS_VALUE, "invalid normalization form");
    return -1;
}

static void ps_put_code(const char *blob, uint16_t off, uint8_t len, PsBuf *out) {
    ps_buf_copy(out, blob + off, (int64_t)len);
}

void ps_unicode_category(int64_t n, const char *s, PsBuf *out) {
    unsigned char c = ps_one(n, s, "unicodedata.category() argument is one character");
    char buf[2];
    uint16_t packed = ps_cat[c];
    buf[0] = (char)(packed >> 8);
    buf[1] = (char)packed;
    ps_buf_copy(out, buf, 2);
}

int64_t ps_unicode_combining(int64_t n, const char *s) {
    unsigned char c = ps_one(n, s, "unicodedata.combining() argument is one character");
    return (int64_t)ps_ccc[c];
}

void ps_unicode_normalize(int64_t fn, const char *form, int64_t n, const char *s, PsBuf *out) {
    int form_id = ps_form_id(fn, form);
    PsGrow grow;
    int64_t i;
    ps_grow_init(&grow);
    for (i = 0; i < n; i++) {
        unsigned char c = (unsigned char)s[i];
        uint16_t tag = ps_norm[form_id][c];
        if (tag & 0x8000u) {
            ps_raise_cstr(PS_VALUE, "normalization leaves Latin-1");
        }
        if (tag & 0x4000u) {
            ps_grow_byte(&grow, (unsigned char)tag);
        } else {
            ps_grow_byte(&grow, c);
        }
    }
    ps_grow_finish(&grow, out);
}

int32_t ps_unicode_is_normalized(int64_t fn, const char *form, int64_t n, const char *s) {
    int form_id = ps_form_id(fn, form);
    int64_t i;
    for (i = 0; i < n; i++) {
        unsigned char c = (unsigned char)s[i];
        if (ps_norm[form_id][c] != 0) {
            return 0;
        }
    }
    return 1;
}

