int ps_str_printable(uint32_t cp) {
    if (cp == 0x20) {
        return 1;
    }
    if (cp < 0x100) {
        uint16_t packed = ps_cat[cp];
        char c0 = (char)(packed >> 8);
        if (c0 == 'C' || c0 == 'Z') {
            return 0;
        }
        return 1;
    }
    /* Control and format pockets above the Latin-1 table, the surrogate
       and private-use planes, and the unassigned noncharacter ranges;
       ranges the Unicode database keeps in the escape-only categories. */
    static const struct {
        uint32_t lo;
        uint32_t hi;
    } escape_only[] = {
        {0x00AD, 0x00AD},   /* soft hyphen (Cf) */
        {0x0600, 0x0605},   /* Arabic number signs (Cf) */
        {0x0890, 0x0891},   /* Arabic pound and piastre marks (Cf) */
        {0x061C, 0x061C},   /* Arabic letter mark (Cf) */
        {0x06DD, 0x06DD},   /* Arabic end of ayah (Cf) */
        {0x070F, 0x070F},   /* Syriac abbreviation mark (Cf) */
        {0x08E2, 0x08E2},   /* Arabic dispute (Cf) */
        {0x180E, 0x180E},   /* Mongolian vowel separator (Cf) */
        {0x200B, 0x200F},   /* ZW space chain (Cf) */
        {0x2028, 0x2028},   /* line separator (Zl) */
        {0x2029, 0x2029},   /* paragraph separator (Zp) */
        {0x1680, 0x1680},   /* Ogham space mark (Zs) */
        {0x2000, 0x200A},   /* the en and em space run (Zs) */
        {0x202F, 0x202F},   /* narrow no-break space (Zs) */
        {0x205F, 0x205F},   /* medium mathematical space (Zs) */
        {0x3000, 0x3000},   /* ideographic space (Zs) */
        {0x202A, 0x202E},   /* bidi controls (Cf) */
        {0x2060, 0x2064},   /* invisible operators (Cf) */
        {0x2066, 0x206F},   /* bidi isolates (Cf) */
        {0xD800, 0xF8FF},   /* surrogates + private use area A (plane 14) */
        {0xF0000, 0xFFFFD}, /* private use planes 15 to 16 */
        {0x100000, 0x10FFFD}, /* private use plane 16 (road signs and symbols) */
        {0xFEFF, 0xFEFF},   /* BOM (Cf) */
        {0xFFF9, 0xFFFB},   /* interlinear annotation (Cf) */
        {0x13430, 0x1343F}, /* Egyptian format controls (Cf) */
        {0x110BD, 0x110BD}, /* Kaithi number sign (Cf) */
        {0x110CD, 0x110CD}, /* Kaithi section sign (Cf) */
        {0x1BCA0, 0x1BCA3}, /* shorthand controls (Cf) */
        {0x1D173, 0x1D17A}, /* musical symbols (Cf) */
        {0xE0001, 0xE0001}, /* language tag (Cf) */
        {0xE0020, 0xE007F}, /* tag characters (Cf) */
    };
    for (size_t i = 0; i < sizeof escape_only / sizeof escape_only[0]; i++) {
        if (cp >= escape_only[i].lo && cp <= escape_only[i].hi) {
            return 0;
        }
    }
    for (int64_t i = 0; i < ps_cn_ranges_n; i++) {
        if (cp >= ps_cn_ranges[i].lo && cp <= ps_cn_ranges[i].hi) {
            return 0;
        }
    }
    return 1;
}

/* CPython's `repr` of a str: the shortest of '...' / "..." carries the
   string, backslashes and the active quote escape, \n \r \t keep their
   letter names, printable code points print as themselves and the rest
   escape as \xNN (below U+0100), \uNNNN (below U+010000) or \UNNNNNNNN.
   Shared by the repr() builtin, the tuple display and the !r conversion. */
void ps_repr_str(int64_t n, const char *p, PsBuf *out) {
    char *q = malloc((size_t)n * 10 + 3);
    if (q == NULL) {
        abort();
    }
    char *w = q;
    int quote = '\'';
    if (memchr(p, '\'', (size_t)n) != NULL && memchr(p, '"', (size_t)n) == NULL) {
        quote = '"';
    }
    *w++ = (char)quote;
    static const char hex[] = "0123456789abcdef";
    int64_t i = 0;
    while (i < n) {
        unsigned char c = (unsigned char)p[i];
        if (c == (unsigned char)quote || c == '\\') {
            *w++ = '\\';
            *w++ = (char)c;
            i++;
            continue;
        }
        if (c == '\n') {
            *w++ = '\\';
            *w++ = 'n';
            i++;
            continue;
        }
        if (c == '\r') {
            *w++ = '\\';
            *w++ = 'r';
            i++;
            continue;
        }
        if (c == '\t') {
            *w++ = '\\';
            *w++ = 't';
            i++;
            continue;
        }
        if (c < 0x80) {
            if (c >= 0x20 && c != 0x7f) {
                *w++ = (char)c;
            } else {
                *w++ = '\\';
                *w++ = 'x';
                *w++ = hex[c >> 4];
                *w++ = hex[c & 15];
            }
            i++;
            continue;
        }
        int width = ps_utf8_len(c);
        uint32_t cp = c & (uint32_t)(0xFF >> (width + 1));
        for (int k = 1; k < width && i + k < n; k++) {
            cp = (cp << 6) | ((unsigned char)p[i + k] & 0x3F);
        }
        if (ps_str_printable(cp) > 0) {
            memcpy(w, p + i, (size_t)width);
            w += width;
        } else if (cp < 0x100) {
            *w++ = '\\';
            *w++ = 'x';
            *w++ = hex[(cp >> 4) & 15];
            *w++ = hex[cp & 15];
        } else if (cp < 0x10000) {
            *w++ = '\\';
            *w++ = 'u';
            *w++ = hex[(cp >> 12) & 15];
            *w++ = hex[(cp >> 8) & 15];
            *w++ = hex[(cp >> 4) & 15];
            *w++ = hex[cp & 15];
        } else {
            *w++ = '\\';
            *w++ = 'U';
            for (int shift = 28; shift >= 0; shift -= 4) {
                *w++ = hex[(cp >> shift) & 15];
            }
        }
        i += width;
    }
    *w++ = (char)quote;
    out->len = w - q;
    out->data = q;
}

static int ps_form_id(int64_t n, const char *s) {
    if (n == 3 && memcmp(s, "NFC", 3) == 0) {
        return 0;
    }
    if (n == 3 && memcmp(s, "NFD", 3) == 0) {
        return 1;
    }
    if (n == 4 && memcmp(s, "NFKC", 4) == 0) {
        return 2;
    }
    if (n == 4 && memcmp(s, "NFKD", 4) == 0) {
        return 3;
    }
    ps_raise_cstr(PS_VALUE, "invalid normalization form");
    return -1;
}

