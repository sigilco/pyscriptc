"""Generated support ledger: docs/support-ledger.json and .md.

    python -m benchmarks.compat2.ledger results.json [--out-dir docs]

One entry per module and category with counts, percent, and a backlog list
(every row that is not yet `pass`). It doubles as the agent work queue.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from benchmarks.compat2.outcomes import CATEGORIES, OUTCOMES, Row

ROOT = Path(__file__).resolve().parents[2]


def module_of(row: Row) -> str:
    """`stdlib.csv.reader` -> csv, `builtins.map` -> builtins, `lang.expr-pow` -> lang."""

    parts = row.id.split(".")
    if parts[0] == "stdlib" and len(parts) > 2:
        return parts[1]
    return parts[0]


def build(rows: list[Row]) -> dict[str, Any]:
    modules: dict[str, dict[str, dict[str, Any]]] = {}
    for row in rows:
        cat = modules.setdefault(module_of(row), {}).setdefault(
            row.category, {"total": 0, "counts": dict.fromkeys(OUTCOMES, 0), "backlog": []}
        )
        cat["total"] += 1
        cat["counts"][row.outcome] += 1
        if row.outcome not in {"pass", "excluded"}:
            cat["backlog"].append({"id": row.id, "status": row.outcome, "code": row.code, "evidence": row.evidence})
    for cats in modules.values():
        for cat in cats.values():
            scored = cat["total"] - cat["counts"]["excluded"]
            cat["percent"] = round(100.0 * cat["counts"]["pass"] / scored, 2) if scored else 0.0
            cat["counts"] = {k: v for k, v in cat["counts"].items() if v}
    return {"modules": dict(sorted(modules.items()))}


def render_md(ledger: dict[str, Any]) -> str:
    lines = [
        "# Support ledger",
        "",
        "Generated by `benchmarks.compat2.ledger`. Do not edit by hand.",
        "",
        "| module | category | pass | total | percent | backlog |",
        "| --- | --- | ---: | ---: | ---: | ---: |",
    ]
    for module, cats in ledger["modules"].items():
        for name in CATEGORIES:
            if name in cats:
                c = cats[name]
                lines.append(
                    f"| {module} | {name} | {c['counts'].get('pass', 0)} | {c['total']} | {c['percent']} "
                    f"| {len(c['backlog'])} |"
                )
    for module, cats in ledger["modules"].items():
        for name in CATEGORIES:
            backlog = cats.get(name, {}).get("backlog", [])
            if backlog:
                lines += ["", f"## {module} {name} backlog", ""]
                lines += [f"- `{b['id']}`: {b['status']} {b['code']}".rstrip() for b in backlog]
    return "\n".join(lines) + "\n"


def write(rows: list[Row], out_dir: Path) -> None:
    ledger = build(rows)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "support-ledger.json").write_text(json.dumps(ledger, indent=2) + "\n", encoding="utf-8")
    (out_dir / "support-ledger.md").write_text(render_md(ledger), encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Write the generated support ledger.")
    parser.add_argument("results")
    parser.add_argument("--out-dir", default=str(ROOT / "docs"))
    args = parser.parse_args(argv)
    data = json.loads(Path(args.results).read_text(encoding="utf-8"))
    write([Row(**r) for r in data["rows"]], Path(args.out_dir))
    return 0


if __name__ == "__main__":
    sys.exit(main())
