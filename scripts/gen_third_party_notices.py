#!/usr/bin/env python3
"""Generate NOTICE: the third-party notice rollup for the shipped compiler.

The compiler is Apache-2.0 (LICENSE). When a release binary embeds a CPython
runtime (the `--embed-python=bundle` slice, docs/reference/runtime-pack.md),
the CPython license and the licenses of the components compiled into libpython
must travel with the binary. The runtime pack carries the full license texts
in its `licenses/` directory; NOTICE is the short rollup that names the
components and points at those texts.

Sources, in priority order:

1. `packaging/runtime.lock.toml`, the pinned python-build-standalone runtime
   the pack is cut from (its CPython micro and PBS release tag).
2. `packaging/third-party.toml`, the curated component inventory of the pack
   build: one `[[components]]` entry per third-party component compiled into
   libpython, with `name`, `version`, `license` (SPDX expression or short
   name) and optional `homepage` and `note`.
3. `LICENSE`, for pyscriptc's own Apache-2.0 line.

The output is deterministic: run it twice, get byte-identical NOTICE. A lock
bump changes the CPython line; a pack inventory change is an inventory change
and goes through `packaging/third-party.toml`, not an edit of NOTICE.

Usage:
    uv run python scripts/gen_third_party_notices.py            # write NOTICE
    uv run python scripts/gen_third_party_notices.py --check    # exit 1 on drift
"""

from __future__ import annotations

import argparse
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCK = ROOT / "packaging" / "runtime.lock.toml"
INVENTORY = ROOT / "packaging" / "third-party.toml"
NOTICE = ROOT / "NOTICE"

HEADER = """\
NOTICE
======

pyscriptc
---------

pyscriptc is licensed under the Apache License, Version 2.0. The license text
is in LICENSE at the root of this repository (and shipped inside the release
binary's own license directory).

Bundled CPython runtime
-----------------------
"""

FOOTER = """\
Full license texts
------------------

The complete license text of CPython and of every component above ships in
the `licenses/` directory of the runtime pack and is copied into
`OUT/share/licenses/` of every output directory built with
`--embed-python=bundle`. This file names the components; the pack carries
the texts. This file is generated by scripts/gen_third_party_notices.py;
edit the inputs, not the output.
"""


def _load(path: Path) -> dict:
    with path.open("rb") as fh:
        return tomllib.load(fh)


def cpython_line(lock: dict) -> str:
    """One line naming the pinned runtime from the lock file."""
    version = lock.get("cpython", {}).get("version", "unknown")
    release = lock.get("release", {}).get("tag") or lock.get("release", {}).get("pbs", "unknown")
    return f"CPython {version} (python-build-standalone release {release})"


def render(lock_path: Path | None, inventory_path: Path) -> str:
    """The full NOTICE text from the lock and the inventory."""
    lines = [HEADER]
    if lock_path is not None and lock_path.exists():
        lines.extend([f"This build bundles {cpython_line(_load(lock_path))}.", ""])
    else:
        lines.extend(["No runtime pack is pinned yet (packaging/runtime.lock.toml is absent).", ""])
    lines.append("Third-party components compiled into the bundled libpython:")
    lines.append("")
    inventory = _load(inventory_path)
    for component in inventory.get("components", []):
        name = component["name"]
        version = component.get("version", "")
        license_id = component.get("license", "unknown")
        label = f"{name} {version}".strip()
        line = f"- {label} -- {license_id}"
        note = component.get("note")
        if note:
            line += f" ({note})"
        lines.append(line)
    lines.extend(["", FOOTER])
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when NOTICE is stale")
    args = parser.parse_args(argv)

    has_lock = LOCK.exists()
    text = render(LOCK if has_lock else None, INVENTORY)
    if args.check:
        current = NOTICE.read_text(encoding="utf-8") if NOTICE.exists() else ""
        if current != text:
            print(
                "NOTICE is stale: run `uv run python scripts/gen_third_party_notices.py`",
                file=sys.stderr,
            )
            return 1
        print("NOTICE is up to date.")
        return 0
    NOTICE.write_text(text, encoding="utf-8")
    print(f"wrote {NOTICE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
