"""HTTPS for the native client: the pyscriptc-http adapter (issue #235).

The tests bind a local TLS listener with a throwaway CA (a self-signed
certificate generated by `openssl` in the test's temp directory), compile a
program against it with the adapter's FFI manifest, and check what the
runtime does:

- certificate verification is ON: a server whose certificate does not chain
  to a root the program trusts raises `URLError`/`OSError` instead of
  returning the body, and so does a certificate for the wrong hostname;
- without the adapter an https:// URL raises with the actionable message
  (fail closed), and an http:// URL still works;
- the positive path (a real host over https) is the opt-in network smoke.

The runtime picks its trust roots from the platform store, so the local
listener's throwaway CA is (deliberately) not trusted: that is what makes
the negative test the meaningful one. The positive path is proved by the
network smoke and, offline, by the adapter's own host-level test.
"""

from __future__ import annotations

import http.server
import os
import re
import shutil
import ssl
import subprocess
import sys
import threading
from pathlib import Path

import pytest
from tests.test_gates import run_cli, write_case

ROOT = Path(__file__).resolve().parents[1]
ADAPTER = ROOT / "packaging" / "adapters" / "pyscriptc-http"
MANIFEST = ADAPTER / "ffi.toml"

FETCH = """
import sys
import urllib.request


def fetch(url: str) -> str:
    r: urllib.request.HTTPResponse = urllib.request.urlopen(url)
    body: bytes = r.read()
    return body.decode("utf-8")


def main() -> int:
    url: str = sys.argv[1]
    r: urllib.request.HTTPResponse = urllib.request.urlopen(url)
    body: bytes = r.read()
    print(r.getcode())
    print(body.decode("utf-8"))
    return 0


if __name__ == "__main__":
    main()
"""

needs_openssl = pytest.mark.skipif(shutil.which("openssl") is None, reason="needs openssl")


def _vendor_available() -> bool:
    """True when the vendored mbedTLS tree is on disk.

    The adapter's `fetch_vendor.py` downloads it (the pin is committed, the
    tree is not). An offline host skips the TLS tests instead of failing.
    """
    return (ADAPTER / "vendor" / "mbedtls" / "library" / "ssl_tls.c").is_file()


needs_vendor = pytest.mark.skipif(not _vendor_available(), reason="the vendored mbedTLS tree is not fetched")


def _make_ca(tmp_path: Path) -> tuple[Path, Path]:
    """A throwaway CA and a server certificate signed by it.

    The CA is a self-signed root; the server certificate carries the
    hostname `localhost` and the loopback address in its subject alt names.
    """
    ca_key = tmp_path / "ca.key"
    ca_crt = tmp_path / "ca.crt"
    srv_key = tmp_path / "server.key"
    srv_csr = tmp_path / "server.csr"
    srv_crt = tmp_path / "server.crt"
    ext = tmp_path / "ext.cnf"
    ext.write_text(
        "subjectAltName=DNS:localhost,IP:127.0.0.1\nbasicConstraints=CA:FALSE\n",
        encoding="utf-8",
    )
    subprocess.run(
        [
            "openssl",
            "req",
            "-x509",
            "-newkey",
            "rsa:2048",
            "-nodes",
            "-keyout",
            str(ca_key),
            "-out",
            str(ca_crt),
            "-days",
            "1",
            "-subj",
            "/CN=pyscriptc-test-ca",
        ],
        check=True,
        capture_output=True,
    )
    subprocess.run(
        [
            "openssl",
            "req",
            "-newkey",
            "rsa:2048",
            "-nodes",
            "-keyout",
            str(srv_key),
            "-out",
            str(srv_csr),
            "-subj",
            "/CN=localhost",
        ],
        check=True,
        capture_output=True,
    )
    subprocess.run(
        [
            "openssl",
            "x509",
            "-req",
            "-in",
            str(srv_csr),
            "-CA",
            str(ca_crt),
            "-CAkey",
            str(ca_key),
            "-CAcreateserial",
            "-out",
            str(srv_crt),
            "-days",
            "1",
            "-extfile",
            str(ext),
        ],
        check=True,
        capture_output=True,
    )
    return ca_crt, srv_crt


class _Handler(http.server.BaseHTTPRequestHandler):
    """One route: the body is fixed, so the test can check it."""

    protocol_version = "HTTP/1.1"

    def log_message(self, *args: object) -> None:  # noqa: D102
        return

    def do_GET(self) -> None:  # noqa: N802
        payload = b"secure hello"
        self.send_response(200)
        self.send_header("Content-Length", str(len(payload)))
        self.end_headers()
        self.wfile.write(payload)


@pytest.fixture(scope="module")
def tls_listener(tmp_path_factory: pytest.TempPathFactory):
    """A TLS listener on loopback with a throwaway CA.

    Yields (url, ca_path). The CA is the only root the server's certificate
    chains to, so a client that trusts the system store rejects it.
    """
    tmp_path = tmp_path_factory.mktemp("tls")
    ca_crt, srv_crt = _make_ca(tmp_path)
    server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), _Handler)
    context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    context.load_cert_chain(certfile=str(srv_crt), keyfile=str(tmp_path / "server.key"))
    server.socket = context.wrap_socket(server.socket, server_side=True)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    port = server.server_address[1]
    yield f"https://localhost:{port}", str(ca_crt)
    server.shutdown()
    server.server_close()


def _case(tmp_path: Path, name: str = "fetch.py") -> Path:
    return write_case(tmp_path, name, FETCH)


def _compile_with_adapter(tmp_path: Path, source: Path, name: str) -> Path:
    """Compile the case with the adapter's manifest, without running it."""
    binary = tmp_path / name
    proc = run_cli(
        "compile",
        str(source),
        "--ffi",
        str(MANIFEST),
        "--emit",
        "bin",
        "-o",
        str(binary),
    )
    assert proc.returncode == 0, proc.stdout + proc.stderr
    return binary


def test_the_client_config_is_client_only() -> None:
    """The committed trim is a client config: no server, no DTLS, 1.2 and 1.3."""
    text = (ADAPTER / "mbedtls_config_client.h").read_text(encoding="utf-8")
    enabled = set(re.findall(r"^#define\s+(MBEDTLS_[A-Z0-9_]+)", text, re.M))
    # The client side is on, the server side is off.
    assert "MBEDTLS_SSL_CLI_C" in enabled
    assert "MBEDTLS_SSL_SRV_C" not in enabled
    # DTLS is off.
    assert "MBEDTLS_SSL_PROTO_DTLS" not in enabled
    # TLS 1.2 and TLS 1.3 are on.
    assert "MBEDTLS_SSL_PROTO_TLS1_2" in enabled
    assert "MBEDTLS_SSL_PROTO_TLS1_3" in enabled
    # The ciphers a public HTTPS endpoint negotiates are on, the rest is off.
    assert "MBEDTLS_AES_C" in enabled
    assert "MBEDTLS_GCM_C" in enabled
    assert "MBEDTLS_CHACHA20_C" in enabled
    assert "MBEDTLS_CAMELLIA_C" not in enabled
    assert "MBEDTLS_DES_C" not in enabled
    assert "MBEDTLS_ARIA_C" not in enabled


def test_the_client_config_matches_the_fetched_tree() -> None:
    """The fetched tree carries the committed trim, byte for byte."""
    fetched = ADAPTER / "vendor" / "mbedtls" / "include" / "mbedtls" / "mbedtls_config.h"
    if not fetched.is_file():
        pytest.skip("the vendored mbedTLS tree is not fetched")
    committed = (ADAPTER / "mbedtls_config_client.h").read_bytes()
    assert fetched.read_bytes() == committed


def test_the_trim_is_reproducible_from_the_fetch() -> None:
    """The unset list the fetch applies is the trim the adapter ships.

    `fetch_vendor.py` reads the committed trim and switches every option it
    lists off, so the fetched tree byte-matches the trim on every host. The
    list is the options the trim comments out, so the two cannot drift.
    """
    sys.path.insert(0, str(ADAPTER))
    try:
        import fetch_vendor
    finally:
        sys.path.pop(0)
    unset = fetch_vendor.client_unset()
    assert unset, "the trim lists no options"
    text = (ADAPTER / "mbedtls_config_client.h").read_text(encoding="utf-8")
    for name in unset:
        assert f"//#define {name}" in text, name


@needs_openssl
@needs_vendor
def test_https_rejects_an_untrusted_certificate(tmp_path: Path, tls_listener: tuple[str, str]) -> None:
    """Verification is ON: the throwaway CA is not in the system store."""
    url, _ca = tls_listener
    path = _case(tmp_path, "fetch_untrusted.py")
    binary = _compile_with_adapter(tmp_path, path, "tls_untrusted")
    proc = subprocess.run([str(binary), url], capture_output=True, text=True)
    assert proc.returncode != 0
    assert "verified" in proc.stdout + proc.stderr


@needs_openssl
@needs_vendor
def test_https_without_the_adapter_fails_closed(tmp_path: Path) -> None:
    """No adapter: an https URL raises with the actionable message."""
    path = _case(tmp_path, "fetch_noadapter.py")
    proc = run_cli(
        "compile",
        str(path),
        "--run",
        "--call",
        "fetch",
        "--args",
        "['https://example.invalid']",
        "-o",
        str(tmp_path / "noadapter"),
    )
    assert proc.returncode != 0
    assert "pyscriptc-http" in proc.stdout + proc.stderr


def test_http_still_works_without_the_adapter(tmp_path: Path) -> None:
    """The plaintext path is unchanged: the seam is additive."""
    path = _case(tmp_path, "fetch_http.py")
    proc = run_cli(
        "compile",
        str(path),
        "--run",
        "--call",
        "fetch",
        "--args",
        "['http://127.0.0.1:1/']",
        "-o",
        str(tmp_path / "http_only"),
    )
    # Port 1 refuses the connection, so the program raises; what matters is
    # that it got past the scheme check (no "needs the adapter" message).
    assert "pyscriptc-http" not in proc.stdout + proc.stderr


@pytest.mark.skipif(
    os.environ.get("PYSC_NETWORK_TESTS") != "1",
    reason="network test: set PYSC_NETWORK_TESTS=1",
)
@needs_vendor
def test_https_real_host(tmp_path: Path) -> None:
    """The real-network smoke: a public host over https.

    Opt-in (the other network lanes in this repo use the same gate), so CI
    never touches the network.
    """
    path = _case(tmp_path, "fetch_real.py")
    binary = _compile_with_adapter(tmp_path, path, "tls_real")
    proc = subprocess.run([str(binary), "https://example.com"], capture_output=True, text=True)
    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert proc.stdout.splitlines()[0] == "200"
